"""
Задание 3: Анализ данных о продуктах питания
- Есть таблица с данными о продуктах питания: «Продукт», «Категория», «Калории», «Белки».
- Создайте DataFrame с не менее чем десятью строками.
- Выведите весь DataFrame.
- Найдите все продукты с калорийностью выше 300.
- Подсчитайте среднее количество белков по категориям.
- Отсортируйте DataFrame по калорийности в порядке убывания.
"""

import pandas as pd


def run_task3():
    print("=" * 60)
    print("ЗАДАНИЕ 3: Данные о продуктах питания")
    print("=" * 60)

    # 1. Создаем DataFrame (11 строк, несколько категорий)
    products_data = {
        "Продукт": [
            "Куриное филе",
            "Говядина",
            "Лосось",
            "Тунец",
            "Творог 5%",
            "Греческий йогурт",
            "Сыр Пармезан",
            "Орехи грецкие",
            "Миндаль",
            "Овсяные хлопья",
            "Гречка",
        ],
        "Категория": [
            "Мясо",
            "Мясо",
            "Рыба",
            "Рыба",
            "Молочные продукты",
            "Молочные продукты",
            "Молочные продукты",
            "Снеки и орехи",
            "Снеки и орехи",
            "Крупы",
            "Крупы",
        ],
        "Калории": [165, 250, 208, 130, 121, 97, 431, 654, 579, 366, 343],
        "Белки": [31.0, 26.0, 20.0, 28.0, 17.0, 9.0, 38.0, 15.0, 21.0, 12.0, 13.0],
    }

    products_df = pd.DataFrame(products_data)

    # 2. Выводим весь DataFrame
    print("\n1. Исходный DataFrame (продукты):")
    print(products_df)

    # 3. Находим все продукты с калорийностью выше 300
    high_calorie_products = products_df[products_df["Калории"] > 300]
    print("\n2. Продукты с калорийностью выше 300 ккал:")
    print(high_calorie_products)

    # 4. Подсчитываем среднее количество белков по категориям
    avg_protein_by_cat = products_df.groupby("Категория")["Белки"].mean()
    print("\n3. Среднее количество белков (г) по категориям:")
    print(avg_protein_by_cat)

    # 5. Сортируем DataFrame по калорийности в порядке убывания (ascending=False)
    sorted_by_calories = products_df.sort_values(by="Калории", ascending=False)
    print("\n4. Таблица продуктов, отсортированная по калорийности (по убыванию):")
    print(sorted_by_calories)

    return products_df


if __name__ == "__main__":
    run_task3()
