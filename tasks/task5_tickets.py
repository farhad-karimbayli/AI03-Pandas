"""
Задание 5: Анализ данных о продажах билетов в кино
- У вас есть таблица продаж билетов: «Фильм», «Город», «Проданные билеты».
- Создайте DataFrame с не менее чем двенадцатью строками.
- Выведите весь DataFrame.
- Подсчитайте общее количество проданных билетов по каждому фильму.
- Подсчитайте общее количество билетов по каждому городу.
- Найдите фильм с наибольшим количеством продаж.
"""

import pandas as pd


def run_task5():
    print("=" * 60)
    print("ЗАДАНИЕ 5: Продажи билетов на фильмы")
    print("=" * 60)

    # 1. Создаем DataFrame (не менее 12 строк, 12 строк)
    tickets_data = {
        "Фильм": [
            "Интерстеллар",
            "Интерстеллар",
            "Интерстеллар",
            "Дюна 2",
            "Дюна 2",
            "Дюна 2",
            "Оппенгеймер",
            "Оппенгеймер",
            "Оппенгеймер",
            "Гладиатор 2",
            "Гладиатор 2",
            "Гладиатор 2",
        ],
        "Город": [
            "Баку",
            "Гянджа",
            "Сумгаит",
            "Баку",
            "Гянджа",
            "Сумгаит",
            "Баку",
            "Гянджа",
            "Сумгаит",
            "Баку",
            "Гянджа",
            "Сумгаит",
        ],
        "Проданные билеты": [
            1200,
            450,
            600,
            2100,
            850,
            1100,
            1800,
            720,
            950,
            1500,
            600,
            800,
        ],
    }

    tickets_df = pd.DataFrame(tickets_data)

    # 2. Выводим весь DataFrame
    print("\n1. Весь DataFrame (продажи билетов):")
    print(tickets_df)

    # 3. Подсчитываем общее количество проданных билетов по каждому фильму
    sales_by_film = tickets_df.groupby("Фильм")["Проданные билеты"].sum()
    print("\n2. Общее количество проданных билетов по каждому фильму:")
    print(sales_by_film)

    # 4. Подсчитываем общее количество билетов по каждому городу
    sales_by_city = tickets_df.groupby("Город")["Проданные билеты"].sum()
    print("\n3. Общее количество билетов по каждому городу:")
    print(sales_by_city)

    # 5. Находим фильм с наибольшим количеством продаж
    top_film = sales_by_film.idxmax()
    top_film_total = sales_by_film.max()
    print(f"\n4. Фильм с наибольшим количеством продаж: «{top_film}» ({top_film_total} билетов)")

    # Альтернатива: отсортированный список всех фильмов по продажам
    print("\n   Рейтинг фильмов по суммарным продажам (по убыванию):")
    print(sales_by_film.sort_values(ascending=False))

    return tickets_df


if __name__ == "__main__":
    run_task5()
