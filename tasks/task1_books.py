"""
Задание 1: Анализ данных о книгах
- Создайте DataFrame с не менее чем шестью строками (поля: «Название», «Автор», «Год издания», «Цена»).
- Выведите весь DataFrame.
- Определите среднюю цену книг.
- Найдите книги, изданные после 2015 года.
- Отсортируйте DataFrame по цене в порядке возрастания.
"""

import pandas as pd


def run_task1():
    print("=" * 60)
    print("ЗАДАНИЕ 1: Данные о книгах")
    print("=" * 60)

    # 1. Создаем исходные данные (не менее 6 строк)
    books_data = {
        "Название": [
            "Мастер и Маргарита",
            "1984",
            "Чистый код",
            "Грокаем алгоритмы",
            "Изучаем Python",
            "Преступление и наказание",
            "Глубокое обучение",
        ],
        "Автор": [
            "Михаил Булгаков",
            "Джордж Оруэлл",
            "Роберт Мартин",
            "Адитья Бхаргава",
            "Марк Лутц",
            "Фёдор Достоевский",
            "Ян Гудфеллоу",
        ],
        "Год издания": [1967, 1949, 2019, 2017, 2020, 1866, 2018],
        "Цена": [450.0, 380.0, 1250.0, 950.0, 1800.0, 350.0, 2100.0],
    }

    books_df = pd.DataFrame(books_data)

    # 2. Выводим весь DataFrame
    print("\n1. Весь DataFrame (книги):")
    print(books_df)

    # 3. Средняя цена книг
    avg_price = books_df["Цена"].mean()
    print(f"\n2. Средняя цена книг: {avg_price:.2f} руб.")

    # 4. Книги, изданные после 2015 года
    books_after_2015 = books_df[books_df["Год издания"] > 2015]
    print("\n3. Книги, изданные после 2015 года:")
    print(books_after_2015)

    # 5. Сортировка по цене в порядке возрастания
    sorted_by_price = books_df.sort_values(by="Цена", ascending=True)
    print("\n4. DataFrame, отсортированный по возрастанию цены:")
    print(sorted_by_price)

    return books_df


if __name__ == "__main__":
    run_task1()
