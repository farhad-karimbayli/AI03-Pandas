"""
Задание 4: Анализ данных о сотрудниках и их проектах
- Собраны данные о сотрудниках и их проектах: «Имя», «Проект», «Часы».
- Создайте DataFrame с не менее чем восьмью строками.
- Выведите исходный DataFrame.
- Подсчитайте общее количество часов по каждому сотруднику.
- Подсчитайте общее количество часов по каждому проекту.
- Найдите сотрудника, затратившего больше всего часов.
"""

import pandas as pd


def run_task4():
    print("=" * 60)
    print("ЗАДАНИЕ 4: Сотрудники и проекты")
    print("=" * 60)

    # 1. Создаем исходный DataFrame (9 строк)
    employees_data = {
        "Имя": [
            "Али",
            "Али",
            "Лейла",
            "Лейла",
            "Мурад",
            "Мурад",
            "Айсель",
            "Эльвин",
            "Эльвин",
        ],
        "Проект": [
            "Веб-платформа",
            "Мобильное приложение",
            "Веб-платформа",
            "Аналитика данных",
            "Мобильное приложение",
            "Информационная безопасность",
            "Аналитика данных",
            "Веб-платформа",
            "Информационная безопасность",
        ],
        "Часы": [40, 35, 30, 25, 45, 20, 50, 15, 30],
    }

    employees_df = pd.DataFrame(employees_data)

    # 2. Выводим исходный DataFrame
    print("\n1. Исходный DataFrame (сотрудники и проекты):")
    print(employees_df)

    # 3. Общее количество часов по каждому сотруднику
    hours_per_employee = employees_df.groupby("Имя")["Часы"].sum()
    print("\n2. Общее количество часов по каждому сотруднику:")
    print(hours_per_employee)

    # 4. Общее количество часов по каждому проекту
    hours_per_project = employees_df.groupby("Проект")["Часы"].sum()
    print("\n3. Общее количество часов по каждому проекту:")
    print(hours_per_project)

    # 5. Сотрудник, затративший больше всего часов
    # Способ А: через idxmax() — возвращает индекс (в данном случае имя сотрудника)
    top_employee = hours_per_employee.idxmax()
    max_hours = hours_per_employee.max()
    print(f"\n4. Сотрудник с наибольшим количеством часов: {top_employee} ({max_hours} ч.)")

    # Способ Б: через сортировку sort_values(ascending=False).head(1)
    print("\n   Альтернатива через sort_values():")
    print(hours_per_employee.sort_values(ascending=False).head(1))

    return employees_df


if __name__ == "__main__":
    run_task4()
